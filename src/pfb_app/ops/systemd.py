"""systemd --user units that keep the UI and the worker running (restart on crash, start at
boot with lingering), plus the nightly backup timer and an alert on a unit that gave up.

`render(...)` returns {file name: text}; scripts/install_user_services.sh writes them (into
~/.config/systemd/user by default, or any --unit-dir) and only then, when asked, runs
systemctl --user. Units (prefix "pfb" by default; a test instance uses another prefix):

Both long-running units restart with a growing delay (RestartSteps up to RestartMaxDelaySec)
and no start limit (StartLimitIntervalSec=0): at boot the UI's Tailscale address may come up
late (network-online.target does not exist in a --user manager), and it keeps trying.

- <p>-worker.service: python -m pfb_app.worker.main. Restart=always; KillMode=mixed so a
  stop sends SIGTERM to the worker alone, which stops its session, the engine's command and
  its own vLLM server through its cleanup (identity-checked), before anything else is killed.
  Exit 75 (another worker holds worker.lock) is not restarted. Exit 143 / 129 (it ended through
  its SIGTERM / SIGHUP cleanup: a stop or restart on purpose) is a success, so no OnFailure= alert.
- <p>-ui.service: streamlit run src/pfb_app/ui/serve.py (entry "serve": the screens plus the
  resumable /pfb-upload endpoint; entry "app": ui/app.py alone) on host:port, as start.sh's
  PFB_UI_ENTRY / PFB_UI_HOST (127.0.0.1 for HTTPS through tailscale serve) / PFB_UI_PORT.
- <p>-backup.service + <p>-backup.timer: python -m pfb_app.ops.backup run, nightly
  (Persistent=true: a night missed while the server was off runs at the next start). It has
  no OnFailure=: a failed backup alerts by itself (ops.backup), once.
- <p>-guard.service + <p>-guard.timer: python -m pfb_app.ops.guard check every GUARD_EVERY
  (OnBootSec after boot): writes <data_dir>/ops_status.txt / .json (worker, screens, disk,
  backup) and raises alerts, independent of the worker. A check never fails the unit.
- <p>-alert@.service: python -m pfb_app.ops.alerts unit-failed %i, the OnFailure= of the
  worker and the UI. systemd runs it on every failure, also right before an automatic
  restart; the alert says which (restarting, given up, or exit 75: another worker runs), and
  repeats at most once per alert_repeat_sec.

Safety (scripts/install_user_services.sh): `preflight` refuses --enable while the settings'
data is in use (a fresh worker beat, a held worker.lock, the UI's port answering), and
`existing_target` refuses to overwrite units written for another checkout unless --force.

Python is the app's own .venv interpreter (no `uv run` at boot: nothing is synced or fetched),
HF_HUB_OFFLINE=1 as in start.sh, VIRTUAL_ENV unset.
"""
import argparse
import socket
import subprocess
import sys
from pathlib import Path

DEFAULT_PATH = "{home}/.local/bin:/usr/local/cuda/bin:/usr/local/bin:/usr/bin:/bin"
WORKER_EXIT_ALREADY_RUNNING = 75   # worker.main EXIT_ALREADY_RUNNING
# the worker leaves a SIGTERM / SIGHUP through its cleanup with exit status 128 + signal
# (worker.session.exit_on_signals): a stop or restart by the operator, not a failure (without
# this systemd marks the unit failed and runs OnFailure=, an alert at every restart)
WORKER_EXIT_SIGTERM = 143
WORKER_EXIT_SIGHUP = 129
HEADER = "# generated by scripts/install_user_services.sh for "
BEAT_FRESH_SEC = 90   # the worker touches its beat every 30 s


def _q(value: str | Path) -> str:
    """Quote one argument for an Exec line (systemd accepts shell-style double quotes)."""
    text = str(value)
    if text and all(c.isalnum() or c in "/._-:+=@,%" for c in text):
        return text
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _env_lines(config: Path | None, path_env: str) -> list[str]:
    lines = ["Environment=HF_HUB_OFFLINE=1", "Environment=PYTHONUNBUFFERED=1",
             f"Environment={_q('PATH=' + path_env)}", "UnsetEnvironment=VIRTUAL_ENV"]
    if config is not None:
        lines.append(f"Environment={_q(f'PFB_CONFIG={config}')}")
    return lines


# the UI entry scripts, as scripts/start.sh's PFB_UI_ENTRY
UI_ENTRIES = {"serve": "src/pfb_app/ui/serve.py", "app": "src/pfb_app/ui/app.py"}


def render(app_dir: Path, *, prefix: str = "pfb", config: Path | None = None,
           host: str = "127.0.0.1", port: int = 8501, max_upload_mb: int = 4096,
           entry: str = "serve", python: Path | None = None, backup_at: str = "*-*-* 03:30:00",
           guard_every: str = "5min", path_env: str | None = None, home: Path | None = None) -> dict[str, str]:
    app_dir = Path(app_dir)
    ui_script = UI_ENTRIES[entry]   # KeyError: neither serve nor app
    python = python or app_dir / ".venv" / "bin" / "python"
    home = home or Path.home()
    path_env = path_env or DEFAULT_PATH.format(home=home)
    settings_arg = f" --settings {_q(config)}" if config is not None else ""
    env = "\n".join(_env_lines(config, path_env))
    on_failure = f"OnFailure={prefix}-alert@%n.service"
    head = f"{HEADER}{app_dir}\n"
    units = {}
    units[f"{prefix}-worker.service"] = f"""{head}[Unit]
Description=PFB app worker ({prefix})
StartLimitIntervalSec=0
{on_failure}

[Service]
Type=simple
WorkingDirectory={_q(app_dir)}
{env}
ExecStart={_q(python)} -m pfb_app.worker.main{settings_arg}
Restart=always
RestartSec=15
RestartSteps=5
RestartMaxDelaySec=300
RestartPreventExitStatus={WORKER_EXIT_ALREADY_RUNNING}
SuccessExitStatus={WORKER_EXIT_SIGTERM} {WORKER_EXIT_SIGHUP}
KillMode=mixed
KillSignal=SIGTERM
TimeoutStopSec=180

[Install]
WantedBy=default.target
"""
    units[f"{prefix}-ui.service"] = f"""{head}[Unit]
Description=PFB app UI ({prefix}, {host}:{port})
StartLimitIntervalSec=0
{on_failure}

[Service]
Type=simple
WorkingDirectory={_q(app_dir)}
{env}
ExecStart={_q(python)} -m streamlit run {ui_script} --server.address {_q(host)} \
--server.port {int(port)} --server.maxUploadSize {int(max_upload_mb)} --server.headless true
Restart=always
RestartSec=5
RestartSteps=5
RestartMaxDelaySec=120
TimeoutStopSec=30

[Install]
WantedBy=default.target
"""
    units[f"{prefix}-backup.service"] = f"""{head}[Unit]
Description=PFB app nightly backup ({prefix})

[Service]
Type=oneshot
WorkingDirectory={_q(app_dir)}
{env}
ExecStart={_q(python)} -m pfb_app.ops.backup{settings_arg} run
Nice=10
IOSchedulingClass=idle
TimeoutStartSec=3600
"""
    units[f"{prefix}-backup.timer"] = f"""{head}[Unit]
Description=PFB app nightly backup timer ({prefix})

[Timer]
OnCalendar={backup_at}
Persistent=true
RandomizedDelaySec=600
Unit={prefix}-backup.service

[Install]
WantedBy=timers.target
"""
    units[f"{prefix}-guard.service"] = f"""{head}[Unit]
Description=PFB app status watch ({prefix})

[Service]
Type=oneshot
WorkingDirectory={_q(app_dir)}
{env}
ExecStart={_q(python)} -m pfb_app.ops.guard{settings_arg} check
Nice=10
TimeoutStartSec=120
"""
    units[f"{prefix}-guard.timer"] = f"""{head}[Unit]
Description=PFB app status watch timer ({prefix})

[Timer]
OnBootSec=3min
OnUnitActiveSec={guard_every}
AccuracySec=30s
Unit={prefix}-guard.service

[Install]
WantedBy=timers.target
"""
    units[f"{prefix}-alert@.service"] = f"""{head}[Unit]
Description=PFB app alert: %i failed ({prefix})

[Service]
Type=oneshot
WorkingDirectory={_q(app_dir)}
{env}
ExecStart={_q(python)} -m pfb_app.ops.alerts{settings_arg} unit-failed %i
"""
    return units


def existing_target(unit_dir: Path, prefix: str) -> Path | None:
    """The app folder this prefix's unit files in `unit_dir` were written for (None: none)."""
    for name in (f"{prefix}-worker.service", f"{prefix}-ui.service",
                 f"{prefix}-backup.service", f"{prefix}-guard.service"):
        try:
            first = (Path(unit_dir) / name).read_text(encoding="utf-8").splitlines()[0]
        except (OSError, IndexError):
            continue
        if first.startswith(HEADER):
            return Path(first[len(HEADER):])
    return None


def same_target(unit_dir: Path, prefix: str, app_dir: Path) -> bool:
    """No units of this prefix in `unit_dir`, or they were written for `app_dir` (both
    compared resolved, so a symlinked checkout is the same one)."""
    target = existing_target(unit_dir, prefix)
    return target is None or target.resolve() == Path(app_dir).resolve()


def _listening(host: str, port: int) -> bool:
    try:
        with socket.create_connection((host, int(port)), timeout=1):
            return True
    except OSError:
        return False


def _default_data_dir() -> Path:
    """The live app's data folder (the built-in default), resolved."""
    from pfb_app.config import Settings   # noqa: PLC0415
    return Settings().data_dir.resolve()


LIVE_SESSIONS = ("pfb-ui", "pfb-worker")


def _tmux_sessions() -> list[str]:
    """The live app's tmux sessions that exist now (scripts/start.sh)."""
    found = []
    for name in LIVE_SESSIONS:
        try:
            if subprocess.run(["tmux", "has-session", "-t", name], capture_output=True,
                              timeout=10).returncode == 0:
                found.append(name)
        except (OSError, subprocess.SubprocessError):
            continue
    return found


def preflight(settings, host: str, port: int, beat_fresh_sec: float = BEAT_FRESH_SEC,
              live_checks=_tmux_sessions) -> list[str]:
    """Why starting a worker and a UI for these settings now would run a second copy on the
    same data ([] when nothing is in use). Read-only: the worker beat, worker.lock (flock
    probe), other processes with app.db open (/proc/*/fd), the UI's host:port, and for the
    default (live) data_dir, whatever the prefix, the tmux sessions pfb-ui / pfb-worker."""
    from datetime import datetime, timezone   # noqa: PLC0415

    from pfb_app.ops.supervise import db_open_by, lock_held   # noqa: PLC0415
    from pfb_app.storage import files   # noqa: PLC0415
    problems = []
    beat = files.worker_beat_at(settings)
    if beat is not None:
        age = (datetime.now(timezone.utc) - beat).total_seconds()
        if age < beat_fresh_sec:
            problems.append(f"ワーカーが動いています（{settings.data_dir} の最後の応答は"
                            f"{age:.0f}秒前）。止めてから{beat_fresh_sec:.0f}秒待って、"
                            "もう一度実行してください。")
    lock = settings.data_dir / "worker.lock"
    try:
        if lock_held(lock):
            problems.append(f"別のワーカーが {lock} を使っています。先に止めてください。")
    except OSError as e:
        problems.append(f"{lock} を確認できません（{type(e).__name__}）。"
                        "ワーカーが止まっているか確かめてください。")
    pids = db_open_by(settings.data_dir / "app.db")
    if pids:
        problems.append(f"データベース（{settings.data_dir / 'app.db'}）をほかのプロセス"
                        f"（pid {', '.join(map(str, pids))}）が開いています。先に止めてください。")
    if _listening(host, port):
        problems.append(f"画面（{host}:{port}）がすでに動いています。先に止めてください"
                        "（scripts/stop.sh、または systemctl --user stop）。")
    if settings.data_dir.resolve() == _default_data_dir():
        for name in live_checks():
            problems.append(f"tmux の {name} が動いています（本番のデータ）。"
                            "先に scripts/stop.sh で止めてください。")
    return problems


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m pfb_app.ops.systemd",
                                     description="write the systemd --user unit files")
    parser.add_argument("--app-dir", required=True)
    parser.add_argument("--out", help="folder to write the unit files into")
    parser.add_argument("--preflight", action="store_true",
                        help="only check that the settings' data is not in use (exit 1 if it is)")
    parser.add_argument("--force", action="store_true",
                        help="overwrite / remove units written for another app folder")
    parser.add_argument("--check-target", action="store_true",
                        help="only check that --out's units of this prefix are this app's")
    parser.add_argument("--prefix", default="pfb")
    parser.add_argument("--config", help="settings YAML for both (PFB_CONFIG)")
    parser.add_argument("--host", default="127.0.0.1")
    parser.add_argument("--port", type=int, default=8501)
    parser.add_argument("--entry", choices=sorted(UI_ENTRIES), default="serve",
                        help="serve: ui/serve.py with /pfb-upload (default); app: ui/app.py")
    parser.add_argument("--max-upload-mb", type=int, default=4096)
    parser.add_argument("--python", help="interpreter (default: <app-dir>/.venv/bin/python)")
    parser.add_argument("--backup-at", default="*-*-* 03:30:00", help="OnCalendar= of the backup")
    parser.add_argument("--guard-every", default="5min", help="how often the status watch runs")
    args = parser.parse_args(argv)
    if not args.prefix.replace("-", "").isalnum():
        parser.error("--prefix: letters, digits and '-' only")
    app_dir = Path(args.app_dir).resolve()
    config = Path(args.config).expanduser().resolve() if args.config else None
    if args.check_target or not args.preflight:
        if not args.out:
            parser.error("--out is required")
        if not args.force and not same_target(Path(args.out), args.prefix, app_dir):
            print(f"{args.out} の {args.prefix} のユニットは別のフォルダ"
                  f"（{existing_target(Path(args.out), args.prefix)}）用です。"
                  "置き換える・消すときは --force を付けてください。", file=sys.stderr)
            return 1
        if args.check_target:
            return 0
    from pfb_app.config import load_settings   # noqa: PLC0415
    if config is not None and not config.is_file():
        print(f"設定ファイルが見つかりません: {config}", file=sys.stderr)
        return 2
    settings = load_settings(config)
    if args.prefix != "pfb" and settings.data_dir.resolve() == _default_data_dir():
        print(f"--prefix {args.prefix} の設定のデータフォルダ（{settings.data_dir}）は本番のデータです。"
              "別のフォルダの設定を --config で指定してください。", file=sys.stderr)
        return 2
    if args.preflight:
        problems = preflight(settings, args.host, args.port)
        for line in problems:
            print(line, file=sys.stderr)
        return 1 if problems else 0
    units = render(app_dir, prefix=args.prefix, config=config, host=args.host, port=args.port,
                   max_upload_mb=args.max_upload_mb, entry=args.entry,
                   python=Path(args.python) if args.python else None, backup_at=args.backup_at,
                   guard_every=args.guard_every)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    for name, text in units.items():
        (out / name).write_text(text, encoding="utf-8")
        print(out / name)
    return 0


if __name__ == "__main__":
    sys.exit(main())

